def apply_overrides(argv):
    sets = {}
    for a in argv:
        if a.startswith('--set'):
            continue
    i = 0
    while i < len(argv):
        if argv[i] == '--set':
            k, v = argv[i + 1].split('=', 1)
            sets[k] = v; i += 2
        else:
            i += 1
    if not sets:
        return
    for n, row in enumerate(INPUTS):
        for k, v in sets.items():
            iid, _, yr = k.partition('@')
            if row[0] != iid:
                continue
            row = list(row)
            if isinstance(row[3], dict):
                if yr:
                    row[3] = dict(row[3]); row[3][int(yr)] = float(v)
                else:  # 整列乘數：--set I09=*0.5
                    if v.startswith('*'):
                        row[3] = {y: x * float(v[1:]) for y, x in row[3].items()}
                    elif v.startswith('+'):
                        row[3] = {y: (x + float(v[1:]) if y >= 2026 else x) for y, x in row[3].items()}
                    else:
                        row[3] = {y: float(v) for y in row[3]}
            else:
                row[3] = float(v)
            INPUTS[n] = row = tuple(row)


# ───────────────────────── 公式迷你語言 ─────────────────────────
# {ID}：逐年列取同年欄；純量取值欄。{ID@-1}：前一年。{ID@2026}：指定年。{ID#lo}／{ID#hi}：Inputs 低／高。
TOK = re.compile(r'\{([A-Z]+\d+)(?:@(-?\d+))?(?:#(lo|hi))?\}')


def ref(tok_id, year, off, which, here_sheet):
    r = REG[tok_id]
    sh = r['sheet']
    pre = '' if sh == here_sheet else f"{sh}!"
    if r['kind'] == 'year':
        y = year
        if off:
            o = int(off)
            y = o if o > 1000 else year + o
        return f"{pre}${YCOL[y]}${r['row']}" if sh != here_sheet else f"{YCOL[y]}{r['row']}"
    if r['kind'] == 'src':
        return f"{pre}$E${r['row']}"
    if r['kind'] == 'tk':
        return f"{pre}$F${r['row']}"
    if r['kind'] == 'inp':
        col = {'lo': 'J', 'hi': 'K'}.get(which, 'D')
        return f"{pre}${col}${r['row']}"
    if r['kind'] == 'inpy':
        y = year
        if off:
            o = int(off); y = o if o > 1000 else year + o
        return f"{pre}${YCOL[y]}${r['row']}"
    raise KeyError(tok_id)


def expand(f, year, here):
    return TOK.sub(lambda m: ref(m.group(1), year, m.group(2), m.group(3), here), f)


